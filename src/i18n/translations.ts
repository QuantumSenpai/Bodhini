export type TranslationKey = keyof typeof copy.en;
export function t(language: AppLanguage, key: TranslationKey): string {
  return copy[language][key] ?? copy.en[key];
}

export function documentTypeLabel(language: AppLanguage, type: string): string {
  if (type === "AADHAAR") return t(language, "docTypeAadhaar");
  if (type === "PAN") return t(language, "docTypePan");
  if (type === "BIRTH_CERTIFICATE") return t(language, "docTypeBirth");
  if (type === "RATION_CARD") return t(language, "docTypeRation");
  if (type === "MARKSHEET") return t(language, "docTypeMarksheet");
  if (type === "DOMICILE") return t(language, "docTypeDomicile");
  return t(language, "docTypeOther");
}

